"""App allowing for live tracking of the system via Streamlit app.

To run need to install streamlit in addition to the molecsim package.

Can easily be achieved by installing all app dependencies:

pip install .[apps]

Then run via:

streamlit run src/apps/stremlit_update.py

Note: Entirely generated by AI but usefull for now.
"""

import os
import time
import pickle
from pathlib import Path

import numpy as np
import streamlit as st

from molecsim.system.calculations import (
    calculate_potential,
    full_potential,
    potential_breakdown,
)
from molecsim.system.data import make_potcall, SystemForces, SystemProperties
from molecsim.system.mutate import mutate_rotate, mutate_translate, propose_new
from molecsim.system.potentials import coulomb, lennard_jones
from molecsim.utils.mc import metropolis
from molecsim.utils.place import randomized_system
from molecsim.utils.parsers import parse_com
from molecsim.utils.plot import plot_system
from molecsim.utils.rng import RNG


def build_system(files: list[str], numbers: list[int], box, temperature, seed: int):
    molecule_list = {parse_com(path): n for path, n in zip(files, numbers, strict=True)}

    prop_h20 = list(molecule_list.keys())[0]
    prop_h20.data.charges = np.array([-2, 1, 1])

    rng = RNG(seed)
    props = SystemProperties(
        molecule_list, np.asarray(box, dtype=float), float(temperature)
    )
    sim = randomized_system(props, rng)

    coulomb_cont = make_potcall(coulomb, props)
    lj_cont = make_potcall(lennard_jones, props)
    forces = SystemForces([coulomb_cont, lj_cont])

    fig, updater = plot_system(sim)

    return sim, props, forces, rng, fig, updater


def ensure_state():
    if "initialized" in st.session_state:
        return

    st.session_state.initialized = False
    st.session_state.sim = None
    st.session_state.props = None
    st.session_state.forces = None
    st.session_state.rng = None
    st.session_state.fig = None
    st.session_state.update_fig = None

    # MC state
    st.session_state.mutation_functions = [mutate_rotate, mutate_translate]
    st.session_state.function_coefficients = np.array([0.5, 1.0], dtype=float)
    st.session_state.recent_acceptance = np.ones(2, dtype=float)
    st.session_state.alpha = 1e-3

    # Checkpointing
    st.session_state.outdir = Path("out")
    st.session_state.outdir.mkdir(parents=True, exist_ok=True)
    st.session_state.save_every_seconds = 60.0
    st.session_state.save_count = 1
    st.session_state.last_save_ns = time.perf_counter_ns()

    # Stats
    st.session_state.accepted = 0
    st.session_state.trials = 0


def init_system(
    files_str: str, numbers_str: str, box_xyz: str, temperature: float, seed: int
):
    files = [s.strip() for s in files_str.split() if s.strip()]
    numbers = [int(x) for x in numbers_str.replace(",", " ").split()]
    if len(files) == 0:
        st.error("Please provide at least one .com file path.")
        return False
    if len(files) != len(numbers):
        st.error("files and numbers must have the same count.")
        return False
    try:
        box = [float(v) for v in box_xyz.replace(",", " ").split()]
        if len(box) != 3:
            raise ValueError
    except Exception:
        st.error("Box must be three numbers: e.g. '10 10 10'.")
        return False

    sim, props, forces, rng, fig, updater = build_system(
        files, numbers, box, temperature, seed
    )
    st.session_state.sim = sim
    st.session_state.props = props
    st.session_state.forces = forces
    st.session_state.rng = rng
    st.session_state.fig = fig
    st.session_state.update_fig = updater

    # Reset MC stats
    st.session_state.recent_acceptance = np.ones(
        len(st.session_state.mutation_functions), dtype=float
    )
    st.session_state.accepted = 0
    st.session_state.trials = 0

    # Initial potentials (optional print to console, and UI metric)
    breakdown = potential_breakdown(sim, forces)
    total = full_potential(sim, forces)
    st.session_state.initial_breakdown = breakdown
    st.session_state.initial_total = total

    # Timer
    st.session_state.last_save_ns = time.perf_counter_ns()

    st.session_state.initialized = True
    return True


def step_once():
    sim = st.session_state.sim
    forces = st.session_state.forces
    rng = st.session_state.rng
    muts = st.session_state.mutation_functions
    coeffs = st.session_state.function_coefficients
    alpha = st.session_state.alpha

    old_molecule, new_molecule, index = propose_new(sim, muts, 1, coeffs, rng)

    old_contrib = calculate_potential(sim.data, old_molecule.data, forces)
    new_contrib = calculate_potential(sim.data, new_molecule.data, forces)
    diff = new_contrib - old_contrib

    decider = metropolis(sim.properties, diff, rng)
    st.session_state.recent_acceptance[index] += alpha * (
        int(decider) - st.session_state.recent_acceptance[index]
    )

    if decider:
        old_molecule.copy_from(new_molecule.data)
        st.session_state.accepted += 1

    st.session_state.trials += 1

    # checkpoint if needed
    now_ns = time.perf_counter_ns()
    if (
        now_ns - st.session_state.last_save_ns
    ) / 1e9 >= st.session_state.save_every_seconds:
        tag = f"{st.session_state.save_count:05d}"
        tmp = st.session_state.outdir / f"state_{tag}.pickle.tmp"
        dst = st.session_state.outdir / f"state_{tag}.pickle"
        with open(tmp, "wb") as f:
            pickle.dump(sim, f, protocol=pickle.HIGHEST_PROTOCOL)
        os.replace(tmp, dst)
        st.session_state.save_count += 1
        st.session_state.last_save_ns = now_ns


# ---------------------------
# UI
# ---------------------------
st.set_page_config(page_title="MC Molecule (Streamlit)", layout="wide")
ensure_state()

st.sidebar.header("Initialization")
files_str = st.sidebar.text_input("COM file paths (space-separated)", value="h2o.com")
numbers_str = st.sidebar.text_input(
    "Molecule counts (space/comma-separated)", value="1"
)
box_xyz = st.sidebar.text_input("Box (Ax Ay Az)", value="10 10 10")
temperature = st.sidebar.number_input(
    "Temperature (K)", min_value=0.0, value=300.0, step=10.0
)
seed = st.sidebar.number_input("RNG seed", min_value=0, value=10, step=1)

if st.sidebar.button("Initialize system", type="primary"):
    if init_system(files_str, numbers_str, box_xyz, temperature, seed):
        st.success("System initialized.")

st.sidebar.header("Monte Carlo")
steps_per_click = st.sidebar.slider("Steps per click", 1, 2000, 50, 1)
autoplay = st.sidebar.checkbox("Autoplay")
fps = st.sidebar.slider("Max redraws per second", 5, 60, 15, 1)
st.sidebar.divider()
st.sidebar.subheader("Mutation weights")
w_rot = st.sidebar.number_input(
    "rotate coeff", value=float(st.session_state.function_coefficients[0]), step=0.1
)
w_trans = st.sidebar.number_input(
    "translate coeff", value=float(st.session_state.function_coefficients[1]), step=0.1
)
if (
    w_rot != st.session_state.function_coefficients[0]
    or w_trans != st.session_state.function_coefficients[1]
):
    st.session_state.function_coefficients = np.array([w_rot, w_trans], dtype=float)

left, right = st.columns([3, 2], gap="large")

with left:
    st.subheader("System view")
    placeholder = st.empty()
    if st.session_state.initialized:
        st.session_state.update_fig(st.session_state.sim)
        placeholder.plotly_chart(st.session_state.fig, use_container_width=True)
    else:
        st.info("Initialize the system to show the plot.")

with right:
    st.subheader("Status")
    if st.session_state.initialized:
        acc_rate = (
            (st.session_state.accepted / st.session_state.trials)
            if st.session_state.trials
            else 0.0
        )
        st.metric(
            "Accepted / Tried",
            f"{st.session_state.accepted} / {st.session_state.trials}",
            f"{acc_rate:.1%}",
        )
        st.write("Recent acceptance (EMA per mutation):")
        st.write(st.session_state.recent_acceptance)

        with st.expander("Initial potential breakdown", expanded=False):
            st.write({name: val for name, val in st.session_state.initial_breakdown})
            st.write({"total": st.session_state.initial_total})

run_cols = st.columns(2)
with run_cols[0]:
    if st.button("Run steps"):
        if not st.session_state.initialized:
            st.error("Initialize the system first.")
        else:
            t0 = time.perf_counter_ns()
            for _ in range(steps_per_click):
                step_once()
            st.session_state.update_fig(st.session_state.sim)
            placeholder.plotly_chart(st.session_state.fig, use_container_width=True)
            t1 = time.perf_counter_ns()
            ms_per_iter = (t1 - t0) / steps_per_click * 1e-6
            st.caption(f"Time per iteration (batch): {ms_per_iter:.3f} ms")

with run_cols[1]:
    st.toggle("Autoplay loop", value=autoplay, key="autoplay_state")

# Throttled autoplay loop (keeps UI responsive)
if st.session_state.get("autoplay_state", False) and st.session_state.initialized:
    start = time.time()
    iters_since_draw = 0
    # do a modest chunk per rerun to avoid blocking
    chunk = max(steps_per_click // 5, 1)
    for _ in range(chunk):
        step_once()
        iters_since_draw += 1
        if (time.time() - start) >= (1.0 / fps):
            st.session_state.update_fig(st.session_state.sim)
            placeholder.plotly_chart(st.session_state.fig, use_container_width=True)
            start = time.time()
            iters_since_draw = 0
    st.rerun()

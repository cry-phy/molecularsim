def apply_plot_persistence(fig: go.Figure) -> None:
    # Keep user interactions (camera/zoom) across data updates & reruns
    fig.update_layout(uirevision="molmc")  # global
    if hasattr(fig.layout, "scene") and fig.layout.scene is not None:
        fig.layout.scene.uirevision = "molmc"


def update_and_render(plot_area) -> None:
    """Update traces (under lock) and render exactly ONCE per rerun."""
    if st.session_state.update_fig is not None and st.session_state.sim is not None:
        with st.session_state.worker_lock:
            maybe_new = st.session_state.update_fig(st.session_state.sim)
        if isinstance(maybe_new, go.Figure) and maybe_new is not st.session_state.fig:
            st.session_state.fig = maybe_new
            st.session_state.apply_camera_next = True

    fig = st.session_state.fig
    if fig is None:
        return

    # Apply cached camera only when a brand-new fig object appears
    if st.session_state.apply_camera_next and st.session_state.scene_camera is not None:
        fig.update_layout(scene_camera=st.session_state.scene_camera)
        st.session_state.apply_camera_next = False

    apply_plot_persistence(fig)

    # IMPORTANT: No explicit key; render exactly once per rerun.
    plot_area.plotly_chart(
        fig,
        width="stretch",
        key="__main_plot__",  # stable element identity across reruns
        config={"scrollZoom": True},  # optional: keep scroll-to-zoom enabled
    )

    # Cache camera AFTER render so future NEW figures can inherit it
    try:
        cam = fig.layout.scene.camera
        if cam:
            st.session_state.scene_camera = dict(cam)
    except Exception:
        pass


